"""Regenerate solver_benchmarks/transforms/sdplib_blocks.py from original SDPLIB files.

The converted JLD2 archive this repository bundles stores every problem as one
dense n x n matrix per constraint and does not record SDPLIB's block
structure. The structure is on the third line of each original ``.dat-s``
file (SDPA sparse format: number of constraints, number of blocks, block
sizes; a negative size is a diagonal block). This script reads those lines
and writes the table the loader uses.

Usage:
  python scripts/make_sdplib_block_table.py DIR > solver_benchmarks/transforms/sdplib_blocks.py

DIR holds ``NAME.dat-s`` files, or files with just their first few lines
(any extension; the stem is the problem name). The originals are at
https://github.com/vsdp/SDPLIB (directory ``data``).
"""

from __future__ import annotations

import re
import sys
from itertools import groupby
from pathlib import Path


def read_block_sizes(path: Path) -> tuple[int, ...]:
    """Block sizes from the header of an SDPA sparse file (or its first lines)."""
    with path.open("r", encoding="utf-8", errors="replace") as handle:
        text = handle.read(1 << 16)
    lines = [
        line for line in text.splitlines()
        if line.strip() and not line.lstrip().startswith(('"', "*"))
    ]
    number = re.compile(r"[-+]?\d+")
    # The header lines hold numbers and separators only; anything else is
    # not an SDPA sparse file.
    if len(lines) < 3 or not all(re.fullmatch(r"[\s\d,+\-(){}]*", line) for line in lines[:2]):
        raise ValueError(f"{path.name}: not an SDPA sparse file header")
    num_blocks = int(number.findall(lines[1])[0])
    sizes: list[int] = []
    cursor = 2
    while len(sizes) < num_blocks:
        sizes.extend(int(token) for token in number.findall(lines[cursor]))
        cursor += 1
    if len(sizes) != num_blocks or any(size == 0 for size in sizes):
        raise ValueError(f"{path.name}: cannot read {num_blocks} block sizes")
    return tuple(sizes)


def _literal(sizes: tuple[int, ...]) -> str:
    """A tuple literal, with runs of four or more equal sizes written as a product."""
    runs = [(size, len(list(group))) for size, group in groupby(sizes)]
    if len(runs) == 1 and runs[0][1] == 1:
        return f"({runs[0][0]},)"
    parts = []
    for size, count in runs:
        if count >= 4:
            parts.append(f"*({size},) * {count}")
        else:
            parts.extend([str(size)] * count)
    # A lone starred run, ``(*(2,) * 6)``, is not a tuple without the comma.
    return "(" + ", ".join(parts) + ("," if len(parts) == 1 else "") + ")"


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    table: dict[str, tuple[int, ...]] = {}
    skipped: list[str] = []
    for path in sorted(Path(argv[1]).iterdir()):
        if path.is_file() and not path.name.startswith("."):
            name = path.name.split(".")[0]
            try:
                table[name] = read_block_sizes(path)
            except (ValueError, IndexError) as exc:
                skipped.append(f"{path.name}: {exc}")
    for message in skipped:
        print(f"skipped {message}", file=sys.stderr)
    print('"""Block structure of the SDPLIB problems, as the original files declare it.')
    print()
    print("Generated by scripts/make_sdplib_block_table.py from the third line of each")
    print("problem's ``.dat-s`` file in SDPLIB 1.2. A positive entry is a positive")
    print("semidefinite block of that order and a negative entry is a diagonal block")
    print("of that many nonnegative variables, in the order they appear in the file.")
    print("Do not edit by hand.")
    print('"""')
    print()
    print("from __future__ import annotations")
    print()
    print("SDPLIB_BLOCK_SIZES: dict[str, tuple[int, ...]] = {")
    for name in sorted(table):
        print(f'    "{name}": {_literal(table[name])},')
    print("}")
    return 1 if skipped else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
